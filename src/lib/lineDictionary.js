// 模糊搜索：支持中文/字母/数字，包含即匹配（不区分大小写）
// 返回匹配项数组（最多 limit 条，默认 20）；query 为空返回前 limit 条
export function searchLines(query, limit = 20) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return LINE_DICTIONARY.slice(0, limit);
  return LINE_DICTIONARY.filter(item => {
    return item.lineName.toLowerCase().includes(q)
      || item.station.toLowerCase().includes(q)
      || item.towerRange.toLowerCase().includes(q)
      || String(item.towerCount).includes(q);
  }).slice(0, limit);
}

// 按线路名称精确查找（可能多条，因为同一线路在不同保线站维护不同区段）
export function findLinesByName(lineName) {
  const n = String(lineName || '').trim();
  if (!n) return [];
  return LINE_DICTIONARY.filter(item => item.lineName === n);
}

// 归一化杆塔区段字符串：去空格、去 #、去前导零
// "0129-0581" / "129-581" / "129#-581#" / "0129#-0581#" 均归一化为 "129-581"
export function normalizeTowerRange(range) {
  if (!range) return '';
  return String(range)
    .replace(/[#\s]/g, '')
    .split(/[-~至到]/)
    .filter(Boolean)
    .map(s => String(parseInt(s, 10) || 0))
    .join('-');
}

// 归一化线路名称字符串：去空格、去 # 号、转小写
// 用于模糊匹配（"500kV 云方甲线" 与 "500kV云方甲线" 视为同一条）
function normalizeNameStr(s) {
  return String(s || '')
    .replace(/[\s#]/g, '')   // 去空格、# 号
    .toLowerCase();
}

// 归一化线路名称：模糊匹配字典，返回字典里的标准名称
// 匹配规则：去空格、# 号、大小写不敏感
// 找到返回标准名称；找不到返回原名称（保持兼容）
// 用途：统计聚合时把用户输入的非标准名称自动归一化为字典标准名称，统一字段
export function normalizeLineName(name) {
  const n = String(name || '').trim();
  if (!n) return n;
  // 精确匹配
  const exact = LINE_DICTIONARY.find(item => item.lineName === n);
  if (exact) return exact.lineName;
  // 模糊匹配：去空格、# 号、大小写不敏感
  const normalized = normalizeNameStr(n);
  const fuzzy = LINE_DICTIONARY.find(item => normalizeNameStr(item.lineName) === normalized);
  if (fuzzy) return fuzzy.lineName;
  // 找不到返回原名称
  return n;
}

// 按 线路名称 + 杆塔区段 查找字典项（支持模糊匹配线路名称）
// 匹配时归一化区段（去 # / 去前导零）+ 归一化线路名称（去空格 / # / 大小写）
// 找到返回字典项，找不到返回 null
// 字典项包含权威的 towerCount（如 500kV群兴#1线 0129-0581 = 455 塔，远比 parseTowerCount 解析的 453 准确）
export function findLineInDict(lineName, towerRange) {
  const n = String(lineName || '').trim();
  if (!n) return null;
  const target = normalizeTowerRange(towerRange);
  if (!target) return null;
  const normalizedN = normalizeNameStr(n);
  return LINE_DICTIONARY.find(item =>
    normalizeNameStr(item.lineName) === normalizedN && normalizeTowerRange(item.towerRange) === target
  ) || null;
}
